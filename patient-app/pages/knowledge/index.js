// 解析内容行为结构化对象（subtitle / list / paragraph）
function _parseContentLines(content) {
  if (!Array.isArray(content)) return []
  // 匹配：数字开头后跟中文标点(点、顿号、空格) 如 "1." "1、" "1 " "10."
  var listPattern = /^(\d+)([\.．、\s])/
  return content.map(function (line) {
    if (line.indexOf("【") === 0) {
      return { type: "subtitle", text: line }
    }
    if (line.indexOf("•") === 0) {
      return { type: "list", text: line }
    }
    if (listPattern.test(line)) {
      return { type: "list", text: line }
    }
    return { type: "paragraph", text: line }
  })
}

Page({
  data: {
    rehabLevel: 0,
    levelTag: "",
    levelTagColor: "#eab308",
    articles: [],
    expandedArticleId: "",
  },

  onShow: function () {
    this.loadRehabLevel()
  },

  loadRehabLevel: function () {
    var that = this
    var patientId = auth.getPatientId()

    auth.request({
      url: auth.API_BASE + "/patients/" + patientId + "/rehab-level",
      method: "GET",
      success: function (response) {
        var respData = response.data
        var level = 3
        if (response.statusCode === 200 && respData && respData.code === 200 && respData.data) {
          level = respData.data.rehab_level
        }
        that._buildArticles(level)
      },
      fail: function () {
        that._buildArticles(3)
      },
    })
  },

  _buildArticles: function (level) {
    var levelData = KNOWLEDGE_BY_LEVEL[level] || KNOWLEDGE_BY_LEVEL[3]
    var levelArticles = levelData.articles || []

    // 合并等级文章 + 通用文章
    var allArticles = []
    for (var i = 0; i < levelArticles.length; i++) {
      allArticles.push({
        id: levelArticles[i].id,
        title: levelArticles[i].title,
        category: levelArticles[i].category,
        summary: levelArticles[i].summary,
        content: levelArticles[i].content,
        parsedContent: _parseContentLines(levelArticles[i].content),
        isLevelSpecific: true,
        expanded: false,
      })
    }
    for (var j = 0; j < COMMON_ARTICLES.length; j++) {
      allArticles.push({
        id: COMMON_ARTICLES[j].id,
        title: COMMON_ARTICLES[j].title,
        category: COMMON_ARTICLES[j].category,
        summary: COMMON_ARTICLES[j].summary,
        content: COMMON_ARTICLES[j].content,
        parsedContent: _parseContentLines(COMMON_ARTICLES[j].content),
        isLevelSpecific: false,
        expanded: false,
      })
    }

    this.setData({
      rehabLevel: level,
      levelTag: levelData.tag,
      levelTagColor: levelData.tagColor,
      articles: allArticles,
    })
  },

  handleToggleArticle: function (event) {
    var id = event.currentTarget.dataset.id
    var articles = this.data.articles
    var newExpanded = id
    // 如果点击的是当前展开的，则折叠
    if (this.data.expandedArticleId === id) {
      newExpanded = ""
    }
    for (var i = 0; i < articles.length; i++) {
      articles[i].expanded = articles[i].id === newExpanded
    }
    this.setData({ articles: articles, expandedArticleId: newExpanded })
  },
})
